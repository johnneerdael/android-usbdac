/// Pinned factual identity match. No bcdDevice bounds were specified by these
/// source rows; `None` means all revisions, never a guessed revision range.
#[derive(Debug, Clone, Copy)]
pub struct SourceQuirkEntry {
    pub vendor_id: u16,
    pub product_id: Option<u16>,
    pub bcd_device_min: Option<u16>,
    pub bcd_device_max: Option<u16>,
    pub reference_only: bool,
    pub flags: &'static [AlsaQuirkFlag],
    pub source_line: u32,
}
impl SourceQuirkEntry {
    pub fn source_url(self) -> String {
        format!("https://github.com/torvalds/linux/blob/c03c1a14507dfaf8b856c2608f9ac216021fc222/sound/usb/quirks.c#L{}", self.source_line)
    }
    pub(crate) fn matches(self, vendor: u16, product: u16, revision: u16) -> bool {
        !self.reference_only
            && self.vendor_id == vendor
            && self.product_id == Some(product)
            && self.bcd_device_min.map_or(true, |min| revision >= min)
            && self.bcd_device_max.map_or(true, |max| revision <= max)
    }
}

